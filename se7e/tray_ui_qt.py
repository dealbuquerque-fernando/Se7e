@dataclass(frozen=True)
class CursorPosition:
    x: int
    y: int


def read_cursor_position() -> CursorPosition:
    x, y = _cursor_position()
    return CursorPosition(x, y)


def _screen_entry_for_cursor(
    cursor: CursorPosition,
):
    app = QApplication.instance()
    if app is None:
        raise RuntimeError("TrayPopup requires an active QApplication")

    entries = tuple(
        (screen, _screen_geometry(screen))
        for screen in app.screens()
    )
    if not entries:
        raise RuntimeError("Qt reported no screens")

    for entry in entries:
        _, geometry = entry
        width_scale, height_scale = _dpi_scale(geometry)
        left = round(geometry.x * width_scale)
        top = round(geometry.y * height_scale)
        right = left + round(geometry.width * width_scale)
        bottom = top + round(geometry.height * height_scale)

        if (
            left <= cursor.x < right
            and top <= cursor.y < bottom
        ):
            return entry

    def distance_squared(entry) -> int:
        _, geometry = entry
        width_scale, height_scale = _dpi_scale(geometry)
        left = round(geometry.x * width_scale)
        top = round(geometry.y * height_scale)
        right = left + round(geometry.width * width_scale)
        bottom = top + round(geometry.height * height_scale)

        nearest_x = min(max(cursor.x, left), right - 1)
        nearest_y = min(max(cursor.y, top), bottom - 1)
        return (
            (cursor.x - nearest_x) ** 2
            + (cursor.y - nearest_y) ** 2
        )

    return min(entries, key=distance_squared)


def _target_bottom_right(work_area: WindowRect):
    def target(rect: WindowRect) -> tuple[int, int]:
        return (
            work_area.right - TRAY_EDGE_MARGIN - rect.width,
            work_area.bottom - TRAY_EDGE_MARGIN - rect.height,
        )

    return target


def _bar_percentage(value, connected: bool) -> float:
    if value is None or not connected:
        return 0
    return max(0, min(100, float(value)))


_ICON_FONT_PATH = resource_dir() / "assets" / "Inconsolata-Bold.ttf"


def make_icon_image(color: str, size: int = 32):
    """The Se7e mark: a dark rounded badge with a bold "7", tinted by
    whatever color the caller already uses for live status (unlike the old
    plain dot, this is a badge with the same color-as-status behavior).

    ``size`` defaults to 32 for the system-tray icon (pystray's native
    resolution, no scaling involved). The window-icon .ico, shown in the
    taskbar/Alt-Tab at much larger sizes, is instead generated by calling
    this at a large size (e.g. 256) and letting Pillow's ICO writer
    downscale — downscaling a crisp large source looks sharp everywhere;
    upscaling a small one (the original bug here) looks pixelated.
    """
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    margin = max(1, round(size / 32))
    draw.rounded_rectangle(
        (
            margin,
            margin,
            size - 1 - margin,
            size - 1 - margin,
        ),
        radius=round(size / 4),
        fill="#14161c",
    )
    try:
        font = ImageFont.truetype(
            str(_ICON_FONT_PATH),
            round(size * 21 / 32),
        )
    except OSError:
        font = ImageFont.load_default()

    text = "7"
    left, top, right, bottom = draw.textbbox(
        (0, 0),
        text,
        font=font,
    )
    x = (size - (right - left)) / 2 - left
    y = (size - (bottom - top)) / 2 - top
    draw.text((x, y), text, font=font, fill=color)
    return img


